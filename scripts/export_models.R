# Export fixed, aggregate model parameters from an author-held rms model file.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop("Usage: Rscript scripts/export_models.R path/to/models.rds")
fitted <- readRDS(args[1])
models <- lapply(fitted$models, function(f) {
  stopifnot(f$non.slopes == 4L, length(f$y) == 94L)
  numeric_predictors <- setdiff(names(f$Design$limits), c("gender", "previous_ibd_related_surge"))
  limits <- lapply(numeric_predictors, function(v) {
    setNames(as.numeric(f$Design$limits[c("Low", "High", "Adjust to"), v]), c("min", "max", "default"))
  })
  names(limits) <- numeric_predictors
  list(intercepts = unname(head(coef(f), f$non.slopes)),
       coefficients = tail(coef(f), ncol(f$x)), age_knots = unname(f$Design$parms$age_years),
       limits = limits)
})
parameters <- list(version = "V2 2026-10-16", development_n = 94L,
  group_boundaries = unname(fitted$cutpoints),
  group_labels = c("CDAI 0 to 23.2", "CDAI >23.2 to 62", "CDAI >62 to 108.8", "CDAI >108.8 to 185", "CDAI >185"),
  models = models)
con <- file("app/model_parameters.R", "w")
writeLines("# Fixed parameters from the five-group week-12 CDAI analysis.\n# Generated by scripts/export_models.R; regenerate rather than edit.\n# Aggregate model parameters only; no patient-level records.\nmodel_parameters <-", con)
dput(parameters, con, control = "exact")
close(con)
check <- new.env()
sys.source("app/model_parameters.R", check)
stopifnot(identical(parameters, check$model_parameters))
cat("Model parameters exported without numerical rounding.\n")
